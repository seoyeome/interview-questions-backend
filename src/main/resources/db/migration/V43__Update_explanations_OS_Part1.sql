  - 자원을 **강제로 회수** 가능하게
  - 단점: 일부 자원은 선점 불가 (프린터 등)

- **순환 대기 부정**:
  - 자원에 **순서를 부여**하고 오름차순으로만 요청
  - 예: R1 < R2 < R3 순서로만 할당
