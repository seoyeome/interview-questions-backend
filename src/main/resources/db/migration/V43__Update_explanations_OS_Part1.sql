'**프로세스의 5가지 상태**

1. **New (생성)**
   - 프로세스가 생성된 상태
   - 메모리 할당 전

2. **Ready (준비)**
   - 실행 준비 완료, CPU 할당 대기 중
   - Ready Queue에서 대기

3. **Running (실행)**
   - CPU를 할당받아 실행 중인 상태
   - 한 순간에 하나의 프로세스만 Running (단일 코어 기준)

4. **Waiting (대기/Blocked)**
   - I/O 작업, 이벤트 대기 등으로 실행 불가능한 상태
   - 작업 완료 후 Ready로 전환

5. **Terminated (종료)**
   - 실행 완료된 상태
   - 자원 회수 대기

**상태 전이**
```
New → Ready → Running → Terminated
       ↑         ↓
       ← Waiting ←
```

- **Dispatch**: Ready → Running (스케줄러가 CPU 할당)
- **Timeout**: Running → Ready (할당 시간 종료, Round Robin)
- **Block**: Running → Waiting (I/O 요청)
- **Wake up**: Waiting → Ready (I/O 완료)'
