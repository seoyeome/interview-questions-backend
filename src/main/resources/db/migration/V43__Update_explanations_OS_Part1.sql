- CPU가 참조하려는 페이지가 **물리 메모리에 없을 때** 발생하는 예외
- 필요한 페이지를 디스크에서 메모리로 로드해야 함

---

**발생 과정**

**1. 페이지 부재 발생**
- CPU가 가상 주소 참조
- 페이지 테이블 확인: **유효 비트(Valid Bit) = 0**
- 해당 페이지가 메모리에 없음을 확인

**2. 인터럽트 발생**
- 하드웨어가 OS에 **페이지 폴트 인터럽트** 전달
- CPU 제어가 OS의 페이지 폴트 핸들러로 이동

**3. 페이지 테이블 검사**
- **잘못된 주소 참조**인지 확인
  - 잘못된 주소 → 프로세스 종료 (Segmentation Fault)
  - 유효한 주소 → 계속 진행

**4. 빈 프레임 찾기**
- **빈 프레임이 있으면**: 해당 프레임 사용
- **빈 프레임이 없으면**: **페이지 교체 알고리즘** 실행
  - 희생 페이지(Victim Page) 선택
  - 희생 페이지가 수정되었으면 디스크에 저장 (Write-back)

**5. 페이지 로드**
- 디스크에서 필요한 페이지를 읽어 메모리에 로드
- **가장 시간이 오래 걸리는 단계** (디스크 I/O)

**6. 페이지 테이블 업데이트**
- 유효 비트를 1로 설정
- 프레임 번호 기록

**7. 명령 재시작**
- 페이지 부재를 일으킨 명령 재실행
- 이제 페이지가 메모리에 있으므로 정상 실행

---

**성능 영향**

- 페이지 부재는 **매우 느림** (디스크 접근 필요)
