'**교착 상태 (Deadlock)란?**
- 두 개 이상의 프로세스가 서로가 가진 자원을 **무한정 대기**하는 상태
- 각 프로세스가 다른 프로세스가 점유한 자원을 요구하며 **영구적으로 대기**

**발생 조건 (4가지 모두 만족 시 발생)**

1. **상호 배제 (Mutual Exclusion)**
   - 자원은 **한 번에 하나의 프로세스만** 사용 가능
   - 예: 프린터, 파일 락

2. **점유와 대기 (Hold and Wait)**
   - 프로세스가 **자원을 점유**한 상태에서 **다른 자원을 대기**
   - 예: P1이 자원 A를 가진 채로 자원 B 대기

3. **비선점 (No Preemption)**
   - 프로세스가 자원을 **강제로 빼앗을 수 없음**
   - 자발적으로 반환할 때까지 대기

4. **순환 대기 (Circular Wait)**
   - 프로세스들이 **순환 형태**로 자원을 대기
   - 예: P1 → P2 → P3 → P1 (자원 요청 관계)

**예시**
```
P1: 자원 A 점유, 자원 B 요청
P2: 자원 B 점유, 자원 A 요청

→ P1과 P2가 서로 대기 (Deadlock)
```

**실생활 비유**
- 좁은 다리에서 양쪽에서 차가 마주침
- 서로 비켜주기를 기다림 → 교착 상태'
