'**주요 CPU 스케줄링 알고리즘**

**1. FCFS (First-Come, First-Served)**
- 도착 순서대로 처리
- **비선점형**
- 단점: Convoy Effect (긴 프로세스 뒤 짧은 프로세스 대기)

**2. SJF (Shortest Job First)**
- 실행 시간이 **가장 짧은** 프로세스 먼저
- **비선점형**
- 장점: 평균 대기 시간 최소
- 단점: Starvation 발생 가능, 실행 시간 예측 어려움

**3. SRTF (Shortest Remaining Time First)**
- SJF의 **선점형** 버전
- 남은 실행 시간이 가장 짧은 프로세스 선택
- 새 프로세스 도착 시 비교하여 전환

**4. Round Robin (RR)**
- 각 프로세스에 **동일한 시간(Time Quantum)** 할당
- **선점형**
- Time Quantum 종료 시 Ready Queue 맨 뒤로 이동
- 장점: 공평, 응답 시간 빠름
- 단점: Time Quantum이 너무 작으면 오버헤드 증가

**5. Priority Scheduling**
- **우선순위**가 높은 프로세스 먼저
- 선점형/비선점형 모두 가능
- 단점: Starvation (낮은 우선순위 프로세스 무한 대기)
- 해결: Aging (대기 시간이 길어지면 우선순위 상승)

**6. Multilevel Queue**
- 여러 개의 Ready Queue (우선순위별)
- 각 큐마다 다른 스케줄링 알고리즘 적용
- 예: Foreground (RR), Background (FCFS)

**7. Multilevel Feedback Queue**
- 프로세스가 **큐 간 이동** 가능
- CPU 시간 많이 사용하면 낮은 우선순위 큐로 이동
- I/O 중심 프로세스는 높은 우선순위 유지'
