  ```
  평균 접근 시간 = (1 - p) × 메모리 접근 시간 + p × 페이지 폴트 처리 시간
  p = 페이지 폴트 발생 확률
  ```

**예시**
- 메모리 접근: 200ns
- 페이지 폴트 처리: 8ms
- 페이지 폴트율: 0.1% (p=0.001)
- 평균 접근 시간 = 0.999 × 200ns + 0.001 × 8,000,000ns = **8,200ns**

