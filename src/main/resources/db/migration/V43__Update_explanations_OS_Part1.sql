**1. FIFO (First-In, First-Out)**
- 가장 먼저 들어온 페이지를 교체
- 구현 간단 (큐 사용)
- 단점: **Belady''s Anomaly** (프레임 수 증가 시 페이지 폴트 증가 가능)
- 성능이 좋지 않아 거의 사용 안 함

---

**2. LRU (Least Recently Used)**
- **가장 오랫동안 사용되지 않은** 페이지를 교체
- 과거 사용 패턴을 기반으로 미래 예측
- 성능 우수, 실제로 많이 사용
- 구현 방법:
  - 카운터 (각 페이지의 마지막 참조 시간 기록)
  - 스택 (참조 시 페이지를 스택 top으로 이동)
- 단점: 오버헤드 큼 (매 참조마다 시간 기록 필요)

---

**3. LFU (Least Frequently Used)**
- **참조 횟수가 가장 적은** 페이지를 교체
- 각 페이지의 참조 횟수 기록
- 단점: 초기에 많이 사용된 페이지가 계속 남아있을 수 있음

---

**4. Optimal (OPT)**
- **앞으로 가장 오랫동안 사용되지 않을** 페이지를 교체
- 이론적으로 **최적**의 성능
- 단점: 미래를 알 수 없어 **구현 불가능**
- 다른 알고리즘의 성능 비교 기준으로 사용

---

**5. Clock (Second Chance)**
- FIFO + LRU의 절충안
- 각 페이지에 **참조 비트(Reference Bit)** 사용
- 동작:
  1. 포인터가 순환하며 페이지 검사
  2. 참조 비트가 1이면 0으로 변경하고 다음 페이지로
  3. 참조 비트가 0이면 해당 페이지 교체
- LRU보다 오버헤드 적음
- 실제 OS에서 많이 사용

---

**6. NRU (Not Recently Used)**
- 참조 비트(R)와 수정 비트(M) 사용
- 우선순위: (R=0, M=0) > (R=0, M=1) > (R=1, M=0) > (R=1, M=1)
- 가장 낮은 우선순위 페이지 교체

