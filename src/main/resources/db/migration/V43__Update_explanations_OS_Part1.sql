'**FCFS (First-Come, First-Served)**

**특징**
- **비선점형** 스케줄링
- 도착한 순서대로 CPU 할당
- 가장 단순한 알고리즘

**장점**
- 구현이 간단
- 공평함 (먼저 온 순서대로)

**단점**
- **Convoy Effect**: 긴 프로세스 뒤에 짧은 프로세스들이 오래 대기
- 평균 대기 시간이 길어질 수 있음
- 응답 시간 예측 어려움

**예시**
```
P1 (24ms) → P2 (3ms) → P3 (3ms)
평균 대기 시간: (0 + 24 + 27) / 3 = 17ms
```

---

**Round Robin (RR)**

**특징**
- **선점형** 스케줄링
- 각 프로세스에 **동일한 Time Quantum** 할당 (예: 10ms)
- Time Quantum 종료 시 다음 프로세스로 전환

**장점**
- **응답 시간**이 빠름 (모든 프로세스가 공평하게 CPU 할당받음)
- 대화형 시스템에 적합

**단점**
- Time Quantum이 너무 작으면 **컨텍스트 스위칭 오버헤드** 증가
- Time Quantum이 너무 크면 FCFS와 유사 (응답 시간 느림)

**Time Quantum 설정**
- 일반적으로 **10-100ms**
- 컨텍스트 스위칭 시간의 10배 정도가 적절

**예시**
```
P1 (24ms), P2 (3ms), P3 (3ms), Time Quantum = 4ms

실행 순서:
P1(4) → P2(3) → P3(3) → P1(4) → P1(4) → P1(4) → P1(4) → P1(4)

평균 대기 시간이 FCFS보다 짧음
```

