'**은행가 알고리즘 (Banker''s Algorithm)**

**목적**
- 교착 상태를 **회피(Avoidance)**하기 위한 알고리즘
- 자원을 할당해도 **안전 상태(Safe State)**를 유지할 수 있는지 검사

**핵심 개념**

**안전 상태(Safe State)**
- 모든 프로세스가 **정상적으로 완료**될 수 있는 상태
- 적어도 하나의 **안전 순서(Safe Sequence)**가 존재

**불안전 상태(Unsafe State)**
- 교착 상태가 **발생할 가능성**이 있는 상태
- 안전 순서가 존재하지 않음

---

**알고리즘 동작 과정**

1. **프로세스가 자원 요청**
2. **요청을 가정하고 할당**
3. **안전성 검사 수행**
   - 현재 가용 자원으로 완료 가능한 프로세스 찾기
   - 완료된 프로세스의 자원 회수
   - 다음 프로세스 검사 반복
4. **안전 상태면 할당, 불안전하면 거부**

---

**필요한 데이터 구조**

- **Available**: 현재 사용 가능한 자원 수
- **Max**: 각 프로세스가 필요한 최대 자원 수
- **Allocation**: 각 프로세스에 이미 할당된 자원 수
- **Need**: 각 프로세스가 추가로 필요한 자원 수 (Need = Max - Allocation)

---

