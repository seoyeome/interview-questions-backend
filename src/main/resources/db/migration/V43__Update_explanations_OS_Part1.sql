'**IPC (Inter-Process Communication)**
- 프로세스 간 데이터를 주고받는 메커니즘입니다

**IPC 방식**

1. **파이프 (Pipe)**
   - 단방향 통신 채널
   - 부모-자식 프로세스 간 통신
   - 예: `ls | grep txt`

2. **Named Pipe (FIFO)**
   - 이름을 가진 파이프
   - 관계없는 프로세스 간 통신 가능

3. **메시지 큐 (Message Queue)**
   - 메시지를 큐에 저장하여 전달
   - 비동기 통신 가능
   - 여러 프로세스가 접근 가능

4. **공유 메모리 (Shared Memory)**
   - 여러 프로세스가 **같은 메모리 영역**을 공유
   - **가장 빠른** IPC 방식
   - 동기화 필요 (세마포어 등)

5. **소켓 (Socket)**
   - 네트워크를 통한 통신
   - 서로 다른 머신의 프로세스 간 통신 가능
   - TCP/UDP 사용

6. **시그널 (Signal)**
   - 특정 이벤트 발생을 알림
   - 예: `SIGKILL`, `SIGTERM`

**선택 기준**
- 속도: 공유 메모리 > 메시지 큐 > 파이프 > 소켓
- 동기화: 공유 메모리는 추가 동기화 필요
- 범위: 소켓은 네트워크 통신 가능'
