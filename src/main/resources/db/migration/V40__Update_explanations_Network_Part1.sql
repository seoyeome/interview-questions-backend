1. **모듈화**: 각 계층이 독립적으로 설계/구현 가능
2. **표준화**: 계층 간 인터페이스가 명확
3. **문제 해결 용이**: 특정 계층의 문제를 독립적으로 디버깅
4. **상호 운용성**: 서로 다른 시스템 간 통신 가능

