- **정의**: 동일한 요청을 **여러 번 수행해도 결과가 같은** 성질
- **수학적 정의**: `f(f(x)) = f(x)`

**네트워크/HTTP에서의 의미**
- 같은 요청을 1번 보내든 100번 보내든 **서버의 상태가 동일**해야 함
- 단, **응답 자체**는 달라질 수 있음 (상태 코드 등)

**HTTP 메서드별 멱등성**

**멱등한 메서드**

**1. GET**
- 조회 요청
- 서버 상태를 변경하지 않음
```http
GET /users/1
GET /users/1
GET /users/1
→ 항상 같은 사용자 정보 반환 (서버 상태 변화 없음)
```

**2. PUT**
- 전체 리소스 교체
- 같은 요청을 여러 번 보내도 최종 상태는 동일
```http
PUT /users/1
{ "name": "홍길동", "age": 30 }

PUT /users/1
{ "name": "홍길동", "age": 30 }
→ 몇 번을 보내도 최종 결과는 동일
```

**3. DELETE**
- 삭제 요청
- 첫 번째는 200 OK, 이후는 404 Not Found일 수 있지만
- **서버 상태**(리소스가 없는 상태)는 동일
```http
DELETE /users/1  → 200 OK (삭제됨)
DELETE /users/1  → 404 Not Found (이미 없음)
→ 최종적으로 리소스는 없는 상태로 동일
```

**4. HEAD, OPTIONS**
- 조회 성격의 메서드
- 서버 상태 변경 없음

**멱등하지 않은 메서드**

**POST**
- 새 리소스 생성
- 매번 새로운 리소스가 생성됨
```http
POST /users
{ "name": "홍길동" }
→ 사용자 1 생성

POST /users
{ "name": "홍길동" }
→ 사용자 2 생성 (중복!)

POST를 5번 → 5개의 리소스 생성 (멱등 X)
```

**PATCH**
- 부분 수정
- 구현에 따라 멱등할 수도, 아닐 수도 있음
```http
# 멱등한 PATCH
PATCH /users/1
{ "age": 30 }
→ 몇 번을 보내도 age=30

# 멱등하지 않은 PATCH
PATCH /users/1
{ "age": "+1" }  # 나이 1살 증가
→ 보낼 때마다 나이가 계속 증가
```

**멱등성 표**

| 메서드  | 멱등성 | 안전성* | 설명                          |
|---------|--------|---------|-------------------------------|
| GET     | O      | O       | 조회만, 상태 변경 없음        |
| HEAD    | O      | O       | 헤더만 조회                   |
| OPTIONS | O      | O       | 메서드 옵션 조회              |
| PUT     | O      | X       | 전체 교체, 여러 번 해도 동일  |
| DELETE  | O      | X       | 삭제, 여러 번 해도 결과 동일  |
| POST    | X      | X       | 생성, 매번 새 리소스 생성     |
| PATCH   | △      | X       | 부분 수정, 구현에 따라 다름   |

\* 안전성(Safe): 서버 상태를 전혀 변경하지 않음

**실무에서 중요한 이유**

**1. 네트워크 재시도 (Retry)**
```
클라이언트가 요청 전송 → 타임아웃
→ 서버는 처리했지만 응답이 안 옴

멱등한 요청(PUT, DELETE):
→ 재시도 해도 안전

멱등하지 않은 요청(POST):
→ 재시도하면 중복 생성 위험
→ Idempotency Key 필요
```

**2. 중복 클릭 방지**
```
사용자가 "결제" 버튼 여러 번 클릭

POST /payments (멱등 X):
→ 여러 번 결제됨 (문제!)

해결책:
1. 멱등성 키(Idempotency Key) 사용
2. 클라이언트에서 버튼 비활성화
3. 서버에서 중복 요청 감지
```

**3. 로드 밸런서/프록시**
- 요청 재전송 시 안전성 보장

**Idempotency Key 패턴**
```http
POST /payments
Idempotency-Key: a1b2c3d4-5678-90ef-ghij-klmnopqrstuv
{ "amount": 10000 }

같은 Idempotency-Key로 재요청:
→ 서버가 중복으로 인식, 첫 번째 결과 반환
```

**실제 예시**

**Stripe (결제) API**
```http
POST /v1/charges
Idempotency-Key: unique-key-123
{
  "amount": 2000,
  "currency": "usd"
}
→ 같은 키로 재요청 시 중복 결제 방지
```

**멱등성 설계 원칙**
1. **GET, PUT, DELETE는 멱등하게 구현**
2. **POST는 Idempotency Key 고려**
3. **PATCH는 가능하면 멱등하게 설계**
   - `{ "age": 30 }` (O)
   - `{ "age": "+1" }` (X)
4. **재시도 로직 설계 시 멱등성 고려**

