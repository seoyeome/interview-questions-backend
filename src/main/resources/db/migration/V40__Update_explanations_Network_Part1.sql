'**ARP (Address Resolution Protocol)**
- **계층**: OSI 2.5계층 (네트워크와 데이터링크 사이)
- **목적**: **IP 주소를 MAC 주소로 변환**

**왜 필요한가?**
- 네트워크 계층(L3)은 **IP 주소**를 사용
- 데이터링크 계층(L2)은 **MAC 주소**를 사용
- 실제 물리적 전송을 위해서는 MAC 주소가 필요
- ARP가 이 둘을 연결해줌

**동작 과정 (예시: 192.168.0.10 → 192.168.0.20으로 패킷 전송)**

**1. ARP 요청 (Broadcast)**
```
