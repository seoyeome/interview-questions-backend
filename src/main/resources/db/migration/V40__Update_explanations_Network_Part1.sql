- TCP 연결을 **수립**하는 과정으로, 클라이언트와 서버가 통신을 시작하기 전 서로의 준비 상태를 확인합니다

**과정**
```
Client                    Server
  │                          │
  │─────① SYN (seq=100)─────→│  "연결하고 싶어요"
  │                          │
  │←────② SYN-ACK───────────│  "OK, 준비됐어요"
  │   (seq=200, ack=101)    │
  │                          │
  │─────③ ACK (ack=201)─────→│  "알겠습니다, 시작!"
  │                          │
  │═══ 연결 수립 완료 ═══════│
```

**1단계: SYN (Synchronize)**
- 클라이언트 → 서버
- "연결 요청합니다"
- 초기 시퀀스 번호(ISN) 전송 (예: seq=100)

**2단계: SYN-ACK**
- 서버 → 클라이언트
- "연결 수락합니다" + "당신 메시지 받았습니다"
- 서버의 초기 시퀀스 번호 (seq=200)
- 클라이언트 시퀀스+1 확인 (ack=101)

**3단계: ACK (Acknowledge)**
- 클라이언트 → 서버
- "당신 메시지도 받았습니다"
- 서버 시퀀스+1 확인 (ack=201)
- **이후 데이터 전송 시작 가능**

**4-way Handshake (TCP 연결 종료)**
- TCP 연결을 **종료**하는 과정으로, 양방향 연결을 안전하게 닫습니다

**과정**
```
Client                    Server
  │                          │
  │─────① FIN (seq=500)─────→│  "나는 보낼 데이터 없어요"
  │                          │
  │←────② ACK (ack=501)──────│  "알겠습니다"
  │                          │
  │                          │  (서버는 아직 보낼 데이터가 있을 수 있음)
  │                          │
  │←────③ FIN (seq=600)──────│  "나도 보낼 데이터 끝"
  │                          │
  │─────④ ACK (ack=601)─────→│  "알겠습니다"
  │                          │
  │═══ 연결 종료 완료 ═══════│
```

**1단계: FIN**
- 클라이언트 → 서버
- "연결 종료하겠습니다" (보낼 데이터 없음)

**2단계: ACK**
- 서버 → 클라이언트
- "종료 요청 확인했습니다"
- 서버는 아직 보낼 데이터가 있을 수 있음 (Half-Close 상태)

**3단계: FIN**
- 서버 → 클라이언트
- "나도 연결 종료하겠습니다" (서버도 데이터 전송 완료)

**4단계: ACK**
- 클라이언트 → 서버
- "종료 확인했습니다"
- 클라이언트는 **TIME_WAIT** 상태로 대기 (약 2MSL, 보통 1~4분)
- 이후 완전 종료

**왜 3-way / 4-way인가?**

**3-way (연결)**: SYN + SYN-ACK를 한 번에 보낼 수 있음
- 서버가 SYN 받으면 바로 자신의 SYN과 ACK를 함께 전송

**4-way (종료)**: FIN과 ACK를 분리해야 함
- 서버가 클라이언트의 FIN을 받아도, **아직 보낼 데이터가 남아있을 수 있음**
- ACK 먼저 보내고, 데이터 전송 완료 후 FIN 전송

**TIME_WAIT 상태가 필요한 이유**
1. 마지막 ACK가 손실되면 서버가 FIN을 재전송하는데, 클라이언트가 즉시 종료하면 응답 못함
2. 같은 포트를 바로 재사용하면 이전 연결의 지연된 패킷과 충돌 가능

**실무 이슈**
- **Too many TIME_WAIT**: 서버에서 연결이 많으면 TIME_WAIT 소켓이 쌓임
  - 해결: SO_REUSEADDR 옵션, 커널 파라미터 조정
- **연결 수립 실패**: SYN Flooding 공격 (SYN만 보내고 ACK 안 보냄)
  - 방어: SYN Cookie, 방화벽'
