- ✅ **낮은 지연시간**: 1ms 이하
- ✅ **낮은 오류율**: 안정적인 물리적 매체
- ✅ **개인/조직 소유**: 직접 관리 및 유지보수
- ✅ **낮은 비용**: 초기 구축 비용만 필요

**기술**
- Ethernet (유선)
- Wi-Fi (무선 - WLAN)
