- **Open Systems Interconnection** 모델로, 네트워크 통신을 **7개의 논리적 계층**으로 나눈 표준 참조 모델입니다
- ISO(국제표준화기구)에서 1984년 발표하여 네트워크 통신 과정을 체계적으로 이해하기 위한 프레임워크입니다

**7계층 구조 (상위 → 하위)**

**7. 응용 계층 (Application Layer)**
- **역할**: 사용자와 직접 상호작용하는 응용 프로그램 서비스 제공
- **프로토콜**: HTTP, HTTPS, FTP, SMTP, DNS, SSH
- **예시**: 웹 브라우저, 이메일 클라이언트

**6. 표현 계층 (Presentation Layer)**
- **역할**: 데이터 형식 변환, 암호화/복호화, 압축/해제
- **기능**: 문자 인코딩(ASCII, UTF-8), 이미지 포맷(JPEG), 암호화(SSL/TLS)
- **목적**: 응용 계층에 독립적인 데이터 표현 제공

**5. 세션 계층 (Session Layer)**
- **역할**: 통신 세션 설정, 유지, 종료 관리
- **기능**: 대화 제어, 동기화, 체크포인트
- **프로토콜**: NetBIOS, RPC

**4. 전송 계층 (Transport Layer)**
- **역할**: 종단 간(end-to-end) 신뢰성 있는 데이터 전송
- **프로토콜**: TCP (신뢰성), UDP (빠른 전송)
- **기능**: 포트 번호, 흐름 제어, 오류 제어, 순서 보장(TCP)
- **PDU**: Segment (TCP), Datagram (UDP)

**3. 네트워크 계층 (Network Layer)**
- **역할**: 패킷의 **경로 설정(라우팅)** 및 논리 주소 지정
- **프로토콜**: IP, ICMP, ARP, OSPF, BGP
- **기능**: IP 주소 관리, 패킷 포워딩, 경로 선택
- **PDU**: Packet
- **장비**: 라우터

**2. 데이터 링크 계층 (Data Link Layer)**
- **역할**: 인접한 노드 간 **물리적 주소(MAC)** 기반 프레임 전송
- **프로토콜**: Ethernet, Wi-Fi (802.11), PPP
- **기능**: MAC 주소, 프레임 구성, 오류 검출(CRC), 흐름 제어
- **PDU**: Frame
- **장비**: 스위치, 브리지

**1. 물리 계층 (Physical Layer)**
- **역할**: 물리적 매체를 통한 **비트 스트림** 전송
- **기능**: 전기 신호, 광 신호, 전파로 변환
- **매체**: 케이블(동축, 광섬유), 무선(Wi-Fi, Bluetooth)
- **장비**: 허브, 리피터, 케이블

