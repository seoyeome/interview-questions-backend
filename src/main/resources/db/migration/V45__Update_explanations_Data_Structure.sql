**동작 흐름**
1) key에 해시 함수 적용 → hash 값 생성
2) hash를 배열 크기에 맞게 변환(보통 mod) → index 계산
3) 해당 index의 버킷에서 값 저장/조회

**성능 포인트**
- 핵심은 해시 함수의 분산 품질과, **로드 팩터(load factor = 저장된 원소 수 / 버킷 수)** 관리입니다.
