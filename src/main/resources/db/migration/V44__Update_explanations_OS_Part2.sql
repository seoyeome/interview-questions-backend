'**스케줄러의 3가지 종류**

OS는 프로세스의 생명 주기 동안 여러 단계에서 스케줄링을 수행합니다.

---

**1. 장기 스케줄러 (Long-term Scheduler, Job Scheduler)**

**역할**
- 디스크의 **작업 큐(Job Queue)**에서 프로세스를 선택하여 메모리에 로드
- **New → Ready** 상태 전환
- 메모리에 올라갈 프로세스 결정

**목적**
- **다중 프로그래밍 정도(Degree of Multiprogramming)** 제어
- 메모리에 동시에 존재하는 프로세스 수 조절
- CPU 바운드 프로세스와 I/O 바운드 프로세스 균형 유지

**특징**
- 실행 빈도: **낮음** (분 단위)
- 현대 시분할 시스템(Time-sharing)에서는 거의 사용 안 함
- 배치 시스템에서 주로 사용

**예시**
- 메모리 여유 있음 → 새 프로세스 로드
- 메모리 부족 → 프로세스 로드 지연

---

**2. 단기 스케줄러 (Short-term Scheduler, CPU Scheduler)**

**역할**
- **Ready Queue**에서 프로세스를 선택하여 CPU 할당
- **Ready → Running** 상태 전환
- 어떤 프로세스를 다음에 실행할지 결정

**목적**
- CPU 이용률 최대화
- 응답 시간 최소화

**특징**
- 실행 빈도: **매우 높음** (밀리초 단위)
- **가장 중요한 스케줄러**
- 스케줄링 알고리즘 사용 (FCFS, RR, SJF 등)

**예시**
- 타임 슬라이스 종료 → 다음 프로세스 선택
- I/O 완료로 프로세스 Ready → 우선순위 비교

---

**3. 중기 스케줄러 (Medium-term Scheduler, Swapper)**

**역할**
- 메모리에 있는 프로세스를 **디스크로 스왑 아웃(Swap out)**
- 또는 디스크에서 메모리로 **스왑 인(Swap in)**
- **Ready → Suspended, Suspended → Ready** 상태 전환

**목적**
- **메모리 부족 문제 해결**
- 다중 프로그래밍 정도 조절
- 메모리 관리

**특징**
