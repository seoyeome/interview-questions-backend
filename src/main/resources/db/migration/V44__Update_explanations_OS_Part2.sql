'**메모리 단편화(Fragmentation)란?**
- 메모리가 충분히 있음에도 불구하고 **할당할 수 없는 상태**
- 메모리 공간이 작은 조각으로 나뉘어져 낭비되는 현상

---

**1. 외부 단편화 (External Fragmentation)**

**정의**
- **프로세스들 사이**에 작은 빈 공간들이 흩어져 있는 상태
- 전체 빈 공간은 충분하지만 **연속된 공간이 부족**하여 할당 불가

**발생 원인**
- 가변 크기 메모리 할당 (세그멘테이션)
- 프로세스 생성/종료 반복

**예시**
```
메모리 상태: [P1(100KB)] [빈공간(50KB)] [P2(200KB)] [빈공간(30KB)] [P3(150KB)]

새 프로세스 요청: 70KB
빈 공간 합계: 80KB (충분)
하지만 연속된 70KB 공간이 없어 할당 불가 → 외부 단편화
```

**해결 방법**
1. **압축(Compaction)**
   - 모든 프로세스를 한쪽으로 이동시켜 빈 공간을 하나로 통합
   - 단점: 오버헤드가 매우 큼 (프로세스 이동 비용)

2. **페이징(Paging)**
   - 고정 크기 블록으로 메모리 관리
   - 외부 단편화 완전 제거

3. **메모리 할당 알고리즘**
   - First-fit, Best-fit, Worst-fit

---

**2. 내부 단편화 (Internal Fragmentation)**

**정의**
- **할당된 메모리 내부**에서 사용되지 않는 공간이 발생
- 필요한 것보다 더 큰 메모리 블록 할당 시 발생

**발생 원인**
- 고정 크기 블록 할당 (페이징)
- 메모리 정렬 요구사항

**예시**
```
페이지 크기: 4KB
프로세스 요청: 10KB

할당: 3페이지 (12KB)
사용: 10KB
낭비: 2KB → 내부 단편화
```

**해결 방법**
1. **페이지 크기 조정**
   - 작은 페이지 크기 사용
   - 단점: 페이지 테이블 크기 증가

2. **세그멘테이션**
   - 필요한 만큼만 할당
   - 하지만 외부 단편화 발생 가능

---

**비교**

| 구분 | 외부 단편화 | 내부 단편화 |
|-----|-----------|-----------|
| 발생 위치 | 프로세스 사이 | 할당된 메모리 내부 |
| 발생 원인 | 가변 크기 할당 | 고정 크기 할당 |
| 해결 방법 | 압축, 페이징 | 작은 블록 크기 |
| 영향 | 새 프로세스 할당 불가 | 메모리 낭비 |
| 발생 기법 | 세그멘테이션 | 페이징 |

