'**캐시의 지역성(Locality) 원리**
- 프로그램이 **특정 데이터나 명령어에 집중적으로 접근**하는 경향
- 캐시 메모리의 **효율성을 높이는 핵심 원리**

---

**1. 시간적 지역성 (Temporal Locality)**

**정의**
- 최근에 참조된 데이터가 **가까운 미래에 다시 참조**될 가능성이 높음
- "한번 사용한 것은 또 사용한다"

**예시**
- **반복문(Loop)**: 같은 변수 반복 접근
  ```c
  for (int i = 0; i < 100; i++) {
      sum += array[i];  // sum 변수가 계속 참조됨
  }
  ```

- **함수**: 자주 호출되는 함수 코드
- **재귀 호출**: 같은 함수 반복 실행

**캐시 활용**
- 최근 사용한 데이터를 캐시에 유지
- LRU 교체 정책이 효과적

---

**2. 공간적 지역성 (Spatial Locality)**

**정의**
- 참조된 데이터 **근처의 데이터**가 곧 참조될 가능성이 높음
- "근처에 있는 것도 사용한다"

**예시**
- **배열 순회**: 연속된 메모리 접근
  ```c
  for (int i = 0; i < 100; i++) {
      sum += array[i];  // array[0], array[1], array[2]... 순차 접근
  }
  ```

- **순차 실행**: 명령어는 보통 순서대로 실행
- **구조체**: 멤버 변수들이 연속된 메모리에 저장

**캐시 활용**
- **캐시 라인(Cache Line)** 개념 사용
- 한 번에 여러 바이트(보통 64바이트)를 가져옴
- 인접 데이터도 함께 캐싱

---

**3. 순차적 지역성 (Sequential Locality)**
- 공간적 지역성의 특수 케이스
- 데이터가 **순차적으로** 접근됨
- 예: 배열을 처음부터 끝까지 순회

---

**지역성 활용 예시**

**좋은 예 (지역성 높음)**
```c
// 캐시 친화적: 행 우선 순회
for (int i = 0; i < N; i++) {
    for (int j = 0; j < N; j++) {
        sum += array[i][j];  // 메모리 순서대로 접근
    }
}
```

**나쁜 예 (지역성 낮음)**
```c
// 캐시 비친화적: 열 우선 순회 (C언어는 행 우선 저장)
for (int j = 0; j < N; j++) {
    for (int i = 0; i < N; i++) {
        sum += array[i][j];  // 메모리 순서 아님, 점프 발생
    }
}
```

---

**프로그래밍 최적화**

**지역성을 높이는 방법**

1. **배열 순회**: 메모리 레이아웃 순서대로
2. **데이터 구조 재배치**: 자주 사용하는 필드를 가까이
3. **루프 융합**: 여러 루프를 하나로 합침
4. **블록화(Blocking)**: 데이터를 캐시 크기에 맞게 분할

**예: 행렬 곱셈 최적화**
```c
// 블록화로 캐시 지역성 향상
for (int ii = 0; ii < N; ii += BLOCK_SIZE) {
    for (int jj = 0; jj < N; jj += BLOCK_SIZE) {
        for (int kk = 0; kk < N; kk += BLOCK_SIZE) {
            for (int i = ii; i < min(ii+BLOCK_SIZE, N); i++) {
                for (int j = jj; j < min(jj+BLOCK_SIZE, N); j++) {
                    for (int k = kk; k < min(kk+BLOCK_SIZE, N); k++) {
                        C[i][j] += A[i][k] * B[k][j];
                    }
                }
            }
        }
    }
}
```

