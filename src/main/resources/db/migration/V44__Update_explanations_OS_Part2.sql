**지역성과 성능**
- 지역성이 높을수록 **캐시 히트율 증가**
- 캐시 히트율이 높을수록 **프로그램 속도 향상**
- 같은 알고리즘도 지역성 고려 여부에 따라 **10배 이상 성능 차이** 가능'
