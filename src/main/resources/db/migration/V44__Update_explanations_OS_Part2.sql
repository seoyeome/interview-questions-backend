- 프로세스가 사용할 수 있는 **메모리 영역의 범위**
- 가상 메모리를 사용하여 각 프로세스마다 **독립적인 주소 공간** 제공

---

**주소 공간 구조 (4개 영역)**

**1. Code (Text) 영역**
- **실행 가능한 코드**가 저장되는 영역
- 컴파일된 기계어 명령어
- **읽기 전용 (Read-only)**: 수정 불가
- 여러 프로세스가 공유 가능 (같은 프로그램 실행 시)

**2. Data 영역**
- **전역 변수, 정적 변수**가 저장되는 영역
- 프로그램 시작 시 할당, 종료 시 해제
- 하위 영역:
  - **Initialized Data**: 초기화된 전역/정적 변수
  - **BSS (Block Started by Symbol)**: 초기화되지 않은 전역/정적 변수 (0으로 초기화)

**3. Heap 영역**
- **동적 할당** 메모리 영역
- `malloc()`, `new` 등으로 할당
- **낮은 주소 → 높은 주소** 방향으로 성장
- 프로그래머가 직접 관리 (할당/해제)
- 해제하지 않으면 **메모리 누수(Memory Leak)** 발생

**4. Stack 영역**
- **지역 변수, 함수 파라미터, 리턴 주소** 저장
- 함수 호출 시 스택 프레임(Stack Frame) 생성
- **높은 주소 → 낮은 주소** 방향으로 성장
- LIFO (Last-In, First-Out) 구조
- 함수 종료 시 자동 해제
- **Stack Overflow**: 스택이 힙과 충돌 (재귀 깊이 너무 깊을 때)

---

**메모리 레이아웃 (낮은 주소 → 높은 주소)**

```
┌─────────────────┐ 낮은 주소
│   Code (Text)   │ 실행 코드
├─────────────────┤
│   Data          │ 전역/정적 변수
│   - Initialized │
│   - BSS         │
├─────────────────┤
│   Heap ↓        │ 동적 할당
│                 │
│    (빈 공간)    │
│                 │
│   Stack ↑       │ 지역 변수
└─────────────────┘ 높은 주소
```

---

**예시 (C 언어)**

