'**캐시 메모리(Cache)란?**
- CPU와 메인 메모리(RAM) 사이에 위치한 **매우 빠른 소용량 메모리**
- 자주 사용되는 데이터를 임시 저장하여 **메모리 접근 속도 향상**

---

**메모리 계층 구조 (속도 순)**

```
CPU 레지스터 (가장 빠름, 가장 작음)
    ↓
L1 캐시 (코어당 독립, ~32KB)
    ↓
L2 캐시 (코어당 독립, ~256KB)
    ↓
L3 캐시 (코어 공유, ~8MB)
    ↓
메인 메모리 (RAM, ~8-32GB)
    ↓
보조 기억장치 (SSD/HDD, ~100GB-1TB, 가장 느림, 가장 큼)
```

---

**동작 원리**

**1. CPU가 데이터 요청**
- 먼저 캐시에서 데이터 검색

**2. 캐시 히트 (Cache Hit)**
- 데이터가 캐시에 **있으면** 바로 사용
- 매우 빠름 (~1ns)

**3. 캐시 미스 (Cache Miss)**
- 데이터가 캐시에 **없으면** 메인 메모리에서 가져옴
- 느림 (~100ns)
- 가져온 데이터를 캐시에 저장 (다음 번 빠른 접근)

---

**성능 지표**

**캐시 히트율 (Hit Ratio)**
```
히트율 = 캐시 히트 횟수 / 전체 메모리 접근 횟수

평균 접근 시간 = (히트율 × 캐시 접근 시간) + (미스율 × 메인 메모리 접근 시간)
```

**예시**
- 캐시 접근 시간: 1ns
- 메모리 접근 시간: 100ns
- 히트율: 90%

평균 접근 시간 = 0.9 × 1ns + 0.1 × 100ns = **10.9ns**

---

**캐시 매핑 방식**

**1. 직접 매핑 (Direct Mapping)**
- 각 메모리 블록이 **정해진 캐시 라인**에만 저장
- 빠르지만 충돌(Conflict) 발생 가능

**2. 완전 연관 매핑 (Fully Associative)**
- 어느 캐시 라인에든 저장 가능
- 유연하지만 검색 느림

**3. 세트 연관 매핑 (Set Associative)**
- 직접 + 완전 연관의 절충안
- N-way Set Associative (예: 4-way)

---

**캐시 교체 정책**
- 캐시가 가득 찼을 때 어떤 데이터를 제거할지 결정
- **LRU (Least Recently Used)**: 가장 오래 사용 안 된 데이터 제거
- **LFU (Least Frequently Used)**: 사용 빈도 낮은 데이터 제거
- **FIFO**: 가장 먼저 들어온 데이터 제거

---

**쓰기 정책**

**1. Write-Through**
- 캐시와 메모리에 **동시에** 쓰기
- 일관성 유지 쉬움
- 느림

**2. Write-Back**
- 캐시에만 쓰고 나중에 메모리에 반영
- 빠름
- 일관성 관리 필요

---

**중요성**
- CPU 속도는 빠르지만 메모리 속도는 상대적으로 느림
- 캐시가 없으면 **병목 현상** 발생
- 히트율 90% 이상이면 성능 크게 향상'
